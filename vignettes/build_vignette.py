"""Render the vignette: run every ```python block in QRscore_source.md and write
QRscore.md with the outputs inserted under each block.

    python vignettes/build_vignette.py

Printed output is shown as text; when a block ends with an expression, its value
is shown too (data frames as Markdown tables). Other code blocks (e.g. bash) are
copied as they are and not run.
"""

import ast
import contextlib
import io
import re
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
SOURCE, TARGET = HERE / "QRscore_source.md", HERE / "QRscore.md"
BLOCK = re.compile(r"```python\n(.*?)```\n", re.S)


def _format(value):
    if isinstance(value, pd.DataFrame):
        return value.to_markdown(floatfmt=".4g") + "\n"
    if isinstance(value, pd.Series):
        return value.to_frame().to_markdown(floatfmt=".4g") + "\n"
    return "```\n" + repr(value) + "\n```\n"


def run_block(code, ns):
    tree = ast.parse(code)
    last = tree.body.pop() if tree.body and isinstance(tree.body[-1], ast.Expr) else None
    out = io.StringIO()
    value = None
    with contextlib.redirect_stdout(out):
        exec(compile(tree, "<vignette>", "exec"), ns)
        if last is not None:
            value = eval(compile(ast.Expression(last.value), "<vignette>", "eval"), ns)
    parts = []
    if out.getvalue():
        parts.append("```\n" + out.getvalue().rstrip("\n") + "\n```\n")
    if value is not None:
        parts.append(_format(value))
    return "\n".join(parts)


def main():
    text = SOURCE.read_text()
    ns = {"__name__": "__main__"}
    rendered, pos = [], 0
    for m in BLOCK.finditer(text):
        rendered.append(text[pos:m.end()])
        result = run_block(m.group(1), ns)
        if result:
            rendered.append("\n" + result)
        pos = m.end()
        print(".", end="", file=sys.stderr, flush=True)
    rendered.append(text[pos:])
    header = ("<!-- Generated by vignettes/build_vignette.py from QRscore_source.md; "
              "edit the source and rebuild. -->\n\n")
    TARGET.write_text(header + "".join(rendered))
    print(f"\nwrote {TARGET}", file=sys.stderr)


if __name__ == "__main__":
    main()
